-- Sudoku.game automatic matchmaking setup
-- Run this once in Supabase Dashboard -> SQL Editor.
-- Also ensure Authentication -> Providers -> Anonymous Sign-ins is enabled.

create table if not exists public.matchmaking_queue (
  id bigint generated by default as identity primary key,
  player_id text not null,
  player_name text,
  rating numeric not null default 2.0,
  time_limit integer not null,
  game_mode text not null,
  difficulty text not null,
  joined_at timestamptz not null default now()
);

alter table public.matchmaking_queue
  add column if not exists player_name text,
  add column if not exists rating numeric not null default 2.0,
  add column if not exists time_limit integer,
  add column if not exists game_mode text,
  add column if not exists difficulty text,
  add column if not exists joined_at timestamptz not null default now();

create index if not exists matchmaking_queue_joined_at_idx
  on public.matchmaking_queue (joined_at);
create index if not exists matchmaking_queue_compatibility_idx
  on public.matchmaking_queue (time_limit, game_mode, difficulty, rating, joined_at);
-- Clean duplicate tickets left by older builds before enforcing one ticket per player.
delete from public.matchmaking_queue a
using public.matchmaking_queue b
where a.player_id = b.player_id and a.id < b.id;

create unique index if not exists matchmaking_queue_one_row_per_player_idx
  on public.matchmaking_queue (player_id);

alter table public.matchmaking_queue enable row level security;

drop policy if exists "queue is publicly readable" on public.matchmaking_queue;
create policy "queue is publicly readable"
  on public.matchmaking_queue for select using (true);

drop policy if exists "users manage only their own queue entries" on public.matchmaking_queue;
create policy "users manage only their own queue entries"
  on public.matchmaking_queue for insert
  with check (player_id = auth.uid()::text);

drop policy if exists "users delete only their own queue entries" on public.matchmaking_queue;
create policy "users delete only their own queue entries"
  on public.matchmaking_queue for delete
  using (player_id = auth.uid()::text);

-- Ensure the room columns used by automatic matchmaking exist.
alter table public.sudoku_rooms add column if not exists host_id uuid references auth.users(id);
alter table public.sudoku_rooms add column if not exists guest_id uuid references auth.users(id);

-- Room policies are intentionally aligned with the app's ownership model.
alter table public.sudoku_rooms enable row level security;
drop policy if exists "public rw" on public.sudoku_rooms;
drop policy if exists "rooms are publicly readable" on public.sudoku_rooms;
create policy "rooms are publicly readable" on public.sudoku_rooms
  for select using (true);
drop policy if exists "only creator can create a room as themselves" on public.sudoku_rooms;
create policy "only creator can create a room as themselves" on public.sudoku_rooms
  for insert with check (auth.uid() = host_id);
drop policy if exists "only participants can update a room" on public.sudoku_rooms;
create policy "only participants can update a room" on public.sudoku_rooms
  for update using (guest_id is null or auth.uid() in (host_id, guest_id))
  with check (auth.uid() in (host_id, guest_id));
drop policy if exists "only participants can delete a room" on public.sudoku_rooms;
create policy "only participants can delete a room" on public.sudoku_rooms
  for delete using (auth.uid() in (host_id, guest_id));

-- Remove old abandoned queue tickets. Safe to run repeatedly.
delete from public.matchmaking_queue
where joined_at < now() - interval '5 minutes';
